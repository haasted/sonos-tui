package movy

import (
	"errors"
	"fmt"
	"strconv"
)

var ErrInvalidColorString = errors.New("movy: invalid color string")

func FromHTML(html string) (Rgb, error) {
	s := html
	if len(s) == 7 && s[0] == '#' {
		s = s[1:]
	}
	if len(s) != 6 {
		return Rgb{}, ErrInvalidColorString
	}
	r, err := parseHexByte(s[0:2])
	if err != nil {
		return Rgb{}, ErrInvalidColorString
	}
	g, err := parseHexByte(s[2:4])
	if err != nil {
		return Rgb{}, ErrInvalidColorString
	}
	b, err := parseHexByte(s[4:6])
	if err != nil {
		return Rgb{}, ErrInvalidColorString
	}
	return Rgb{R: r, G: g, B: b}, nil
}

func parseHexByte(s string) (uint8, error) {
	v, err := strconv.ParseUint(s, 16, 8)
	if err != nil {
		return 0, err
	}
	return uint8(v), nil
}

func (c Rgb) String() string {
	return fmt.Sprintf("#%02x%02x%02x", c.R, c.G, c.B)
}

func BrighterFast(c Rgb, amount uint8) Rgb {
	return Rgb{addClamp(c.R, amount), addClamp(c.G, amount), addClamp(c.B, amount)}
}

func DarkerFast(c Rgb, amount uint8) Rgb {
	return Rgb{subClamp(c.R, amount), subClamp(c.G, amount), subClamp(c.B, amount)}
}

func addClamp(v, amount uint8) uint8 {
	if int(v)+int(amount) > 255 {
		return 255
	}
	return v + amount
}

func subClamp(v, amount uint8) uint8 {
	if v < amount {
		return 0
	}
	return v - amount
}

func Brighter(c Rgb, amount uint8) Rgb {
	amt := float32(amount) / 100.0
	rAdd := uint8(float32(255-c.R) * amt)
	gAdd := uint8(float32(255-c.G) * amt)
	bAdd := uint8(float32(255-c.B) * amt)
	return Rgb{addClamp(c.R, rAdd), addClamp(c.G, gAdd), addClamp(c.B, bAdd)}
}

func Darker(c Rgb, amount uint8) Rgb {
	amt := float32(amount) / 100.0
	rSub := uint8(float32(c.R) * amt)
	gSub := uint8(float32(c.G) * amt)
	bSub := uint8(float32(c.B) * amt)
	return Rgb{subClamp(c.R, rSub), subClamp(c.G, gSub), subClamp(c.B, bSub)}
}

